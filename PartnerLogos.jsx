// Helper component to render logo by platform name key
export function PartnerLogo({ platform, size = 26, className = "" }) {
  const p = (platform || "").toLowerCase();
  const style = { width: size, height: size, flexShrink: 0, borderRadius: '4px' };

  if (p.includes("booking")) return <BookingComLogo className={className} style={style} />;
  if (p.includes("agoda")) return <AgodaLogo className={className} style={style} />;
  if (p.includes("makemytrip") || p.includes("mmt")) return <MakeMyTripLogo className={className} style={style} />;
  if (p.includes("easemytrip") || p.includes("emt")) return <EaseMyTripLogo className={className} style={style} />;
  if (p.includes("irctc")) return <IRCTCLogo className={className} style={style} />;
  if (p.includes("confirmtkt") || p.includes("confirm")) return <ConfirmTktLogo className={className} style={style} />;
  if (p.includes("ixigo")) return <IxigoLogo className={className} style={style} />;
  if (p.includes("yatra")) return <YatraLogo className={className} style={style} />;
  if (p.includes("indigo")) return <IndiGoLogo className={className} style={style} />;
  if (p.includes("air india") || p.includes("airline")) return <AirIndiaLogo className={className} style={style} />;

  // Default fallback travel emblem logo
  return (
    <svg className={className} style={style} viewBox="0 0 100 100" fill="none" xmlns="http://www.w3.org/2000/svg">
      <rect width="100" height="100" rx="12" fill="#0B221D"/>
      <circle cx="50" cy="50" r="30" stroke="#C4963D" strokeWidth="6"/>
      <path d="M50 30L60 50L50 70L40 50Z" fill="#C4963D"/>
    </svg>
  );
}
